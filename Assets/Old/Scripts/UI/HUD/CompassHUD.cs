using System.Collections.Generic;
using UnityEngine;
using UnityEngine.UI;
//Don't use this in the main game CODE it's AI;
/// <summary>
/// Procedural digital compass tape built from instantiated UI GameObjects.
/// Attach to a RectTransform that acts as the visible tape window.
/// Add a Mask component to that same object to clip ticks outside the bounds.
///
/// Drive heading via SetHeading() or the public field.
/// No external prefabs required — everything is built at runtime.
/// </summary>
///
[RequireComponent(typeof(RectTransform))]
public class CompassJet : MonoBehaviour
{
    // ?? Input ?????????????????????????????????????????????????????????????????

    [Tooltip("Current aircraft heading in degrees (0–360).")]
    public float heading = 0f;

    // ?? Layout ????????????????????????????????????????????????????????????????

    [Header("Layout")]
    public float compassWidth = 480f;
    public float compassHeight = 56f;

    [Tooltip("How many degrees are visible across the full tape width.")]
    public float degreesShown = 60f;

    [Tooltip("Degrees between major ticks (these get labels).")]
    public int majorTickStep = 10;

    [Tooltip("Degrees between minor ticks. Must divide majorTickStep.")]
    public int minorTickStep = 5;

    // ?? Tick / Label Sizing ???????????????????????????????????????????????????

    [Header("Tick Sizes")]
    public float majorTickWidth = 2f;
    public float majorTickHeight = 20f;
    public float minorTickWidth = 1f;
    public float minorTickHeight = 10f;
    public int labelFontSize = 11;
    public float labelWidth = 36f;
    public float labelHeight = 14f;

    // ?? Colors ????????????????????????????????????????????????????????????????

    [Header("Colors")]
    public Color bgColor = new Color(0.04f, 0.04f, 0.04f, 0.82f);
    public Color tickColor = new Color(0.00f, 1.00f, 0.45f, 1.00f);
    public Color centerMarkColor = new Color(1.00f, 0.22f, 0.08f, 1.00f);

    // ?????????????????????????????????????????????????????????????????????????
    //  Internal pool
    // ?????????????????????????????????????????????????????????????????????????

    struct TickEntry
    {
        public RectTransform tickRT;
        public Image tickImg;
        public RectTransform labelRT;
        public Text labelText;
    }

    RectTransform _root;
    List<TickEntry> _pool = new List<TickEntry>();
    RectTransform _centerMarkRT;

    float _pxPerDeg;

    // ?????????????????????????????????????????????????????????????????????????
    //  Lifecycle
    // ?????????????????????????????????????????????????????????????????????????

    void Awake()
    {
        _root = GetComponent<RectTransform>();
        _root.SetSizeWithCurrentAnchors(RectTransform.Axis.Horizontal, compassWidth);
        _root.SetSizeWithCurrentAnchors(RectTransform.Axis.Vertical, compassHeight);

        SpawnBackground();
        SpawnPool();
        SpawnCenterMark();   // spawned last so it renders on top
    }

    void LateUpdate()
    {
        _pxPerDeg = compassWidth / degreesShown;
        RefreshTicks();
    }

    // ?? Public API ????????????????????????????????????????????????????????????

    public void SetHeading(float deg) => heading = Wrap360(deg);

    // ?????????????????????????????????????????????????????????????????????????
    //  Spawn helpers  (called once)
    // ?????????????????????????????????????????????????????????????????????????

    void SpawnBackground()
    {
        var go = MakeChild("BG");
        var img = go.AddComponent<Image>();
        img.color = bgColor;

        // Stretch to fill parent
        var rt = go.GetComponent<RectTransform>();
        rt.anchorMin = Vector2.zero;
        rt.anchorMax = Vector2.one;
        rt.offsetMin = Vector2.zero;
        rt.offsetMax = Vector2.zero;

        go.transform.SetAsFirstSibling();
    }

    void SpawnCenterMark()
    {
        // Simple downward bar from top center — swap this for a sprite if you have one
        var go = MakeChild("CenterMark");
        var img = go.AddComponent<Image>();
        img.color = centerMarkColor;

        _centerMarkRT = go.GetComponent<RectTransform>();

        // Anchor to top-center, pivot at top so it hangs downward
        _centerMarkRT.anchorMin = new Vector2(0.5f, 1f);
        _centerMarkRT.anchorMax = new Vector2(0.5f, 1f);
        _centerMarkRT.pivot = new Vector2(0.5f, 1f);
        _centerMarkRT.anchoredPosition = Vector2.zero;
        _centerMarkRT.sizeDelta = new Vector2(2f, compassHeight * 0.4f);
    }

    void SpawnPool()
    {
        // Pool one entry per possible visible minor tick, plus a 2-tick buffer each side
        int count = Mathf.CeilToInt(degreesShown / minorTickStep) + 4;

        Font builtinFont = Resources.GetBuiltinResource<Font>("LegacyRuntime.ttf");

        for (int i = 0; i < count; i++)
        {
            // ?? Tick bar ??????????????????????????????????????????????????????
            var tickGO = MakeChild($"Tick_{i}");
            var tickImg = tickGO.AddComponent<Image>();
            tickImg.color = tickColor;

            var tickRT = tickGO.GetComponent<RectTransform>();
            tickRT.anchorMin = Vector2.zero;   // bottom-left of parent
            tickRT.anchorMax = Vector2.zero;
            tickRT.pivot = new Vector2(0.5f, 0f);   // centred horizontally, grows up

            // ?? Label ?????????????????????????????????????????????????????????
            var lblGO = MakeChild($"Label_{i}");
            var lbl = lblGO.AddComponent<Text>();
            lbl.font = builtinFont;
            lbl.fontSize = labelFontSize;
            lbl.color = tickColor;
            lbl.alignment = TextAnchor.LowerCenter;

            var lblRT = lblGO.GetComponent<RectTransform>();
            lblRT.anchorMin = Vector2.zero;
            lblRT.anchorMax = Vector2.zero;
            lblRT.pivot = new Vector2(0.5f, 1f);     // hangs down from anchor point
            lblRT.sizeDelta = new Vector2(labelWidth, labelHeight);

            _pool.Add(new TickEntry
            {
                tickRT = tickRT,
                tickImg = tickImg,
                labelRT = lblRT,
                labelText = lbl,
            });
        }
    }

    // ??? Utility: create a child GO with a RectTransform ?????????????????????

    GameObject MakeChild(string goName)
    {
        var go = new GameObject(goName, typeof(RectTransform));
        go.transform.SetParent(transform, false);
        return go;
    }

    // ?????????????????????????????????????????????????????????????????????????
    //  Refresh (called every LateUpdate)
    // ?????????????????????????????????????????????????????????????????????????

    void RefreshTicks()
    {
        float halfView = degreesShown * 0.5f;

        // First degree value to the left of the visible window
        int dStart = Mathf.FloorToInt((heading - halfView) / minorTickStep) * minorTickStep;
        int dEnd = dStart + Mathf.CeilToInt(degreesShown / minorTickStep) * minorTickStep
                            + minorTickStep;   // one extra to cover the right edge

        int poolIdx = 0;

        for (int d = dStart; d <= dEnd; d += minorTickStep)
        {
            if (poolIdx >= _pool.Count) break;

            var entry = _pool[poolIdx++];
            bool isMajor = (d % majorTickStep == 0);
            float xPos = LocalX(d);

            // ?? Tick ?????????????????????????????????????????????????????????
            entry.tickRT.anchoredPosition = new Vector2(xPos, 0f);
            entry.tickRT.sizeDelta = isMajor
                ? new Vector2(majorTickWidth, majorTickHeight)
                : new Vector2(minorTickWidth, minorTickHeight);
            entry.tickImg.enabled = true;

            // ?? Label  (major ticks only, positioned near top edge) ???????????
            if (isMajor)
            {
                entry.labelText.text = GetLabel(Wrap360(d));
                entry.labelText.enabled = true;
                // Anchor point is at (0,0) = bottom-left; pivot is top-center of label
                // so we push y up to the top of the tape
                entry.labelRT.anchoredPosition = new Vector2(xPos, compassHeight);
            }
            else
            {
                entry.labelText.text = "";
                entry.labelText.enabled = false;
            }
        }

        // Hide any unused pool entries this frame
        for (int i = poolIdx; i < _pool.Count; i++)
        {
            _pool[i].tickImg.enabled = false;
            _pool[i].labelText.enabled = false;
        }
    }

    // ?????????????????????????????????????????????????????????????????????????
    //  Helpers
    // ?????????????????????????????????????????????????????????????????????????

    /// Local x position from the left edge of the tape RectTransform.
    float LocalX(float deg)
    {
        float delta = DeltaDeg(deg, heading);     // signed degrees from current heading
        return compassWidth * 0.5f + delta * _pxPerDeg;
    }

    string GetLabel(float d)
    {
        d = Wrap360(d);
        if (d < 2f || d > 358f) return "N";
        if (d > 88f && d < 92f) return "E";
        if (d > 178f && d < 182f) return "S";
        if (d > 268f && d < 272f) return "W";
        int snapped = Mathf.RoundToInt(d / majorTickStep) * majorTickStep;
        return (((snapped % 360) + 360) % 360).ToString("000");
    }

    static float Wrap360(float d) => ((d % 360f) + 360f) % 360f;

    /// Shortest signed angular difference from <to>. Result in (?180, +180].
    static float DeltaDeg(float from, float to)
    {
        float d = from - to;
        while (d > 180f) d -= 360f;
        while (d < -180f) d += 360f;
        return d;
    }
}



